#!/usr/bin/env node
// Builds PassTech's gear checking (src/engine/index.ts: rulesets, standards, the matcher) into one
// browser script, window.PassTechEngine, for the Digital logbooks app's tech sheet -- so a
// scrutineer's sheet judges each gear line exactly as PassTech does.
//
// Usage: npm run build-engine [-- path/to/output.js]   (default ../logbook-app/passtech-engine.js)

import { build } from "esbuild";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUT = path.resolve(process.argv[2] ?? path.join(ROOT, "..", "logbook-app", "passtech-engine.js"));

await build({
  entryPoints: [path.join(ROOT, "src", "engine", "index.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  globalName: "PassTechEngine",
  target: "es2019",
  alias: { "@": path.join(ROOT, "src") },
  banner: { js: "// GENERATED by PassTech's scripts/build-engine.mjs from src/engine/index.ts -- do not edit." },
  outfile: OUT,
  logLevel: "info",
});
