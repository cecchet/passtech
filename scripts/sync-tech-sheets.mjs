#!/usr/bin/env node
// Copies the built-in tech sheet templates from the Digital logbooks app
// (../logbook-app/tech-sheets/templates/*.json) into src/data/techSheets/ and regenerates
// src/data/techSheets/index.ts, which exports them as BUILTIN_TECH_SHEETS.
//
// Usage: node scripts/sync-tech-sheets.mjs [path/to/templates]
//
// The templates are the record of truth in the logbook app (FORMAT.md there documents them);
// PassTech keeps a copy so the tech-sheet mode works offline and without an event on the server.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, unlinkSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.resolve(process.argv[2] ?? path.join(ROOT, "..", "logbook-app", "tech-sheets", "templates"));
const DEST = path.join(ROOT, "src", "data", "techSheets");

if (!existsSync(SRC)) {
  console.error(`Template folder not found: ${SRC}`);
  process.exit(1);
}
mkdirSync(DEST, { recursive: true });

const files = readdirSync(SRC)
  .filter((f) => f.endsWith(".json"))
  .sort();

const entries = [];
for (const file of files) {
  const raw = readFileSync(path.join(SRC, file), "utf8").replace(/^﻿/, "");
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    console.error(`Skipping ${file}: invalid JSON (${err.message})`);
    continue;
  }
  if (parsed.format !== 1 || typeof parsed.id !== "string" || !Array.isArray(parsed.sections)) {
    console.error(`Skipping ${file}: not a format-1 tech sheet template`);
    continue;
  }
  writeFileSync(path.join(DEST, file), JSON.stringify(parsed, null, 2) + "\n");
  entries.push({ file, id: parsed.id });
}

// Drop copies of templates that no longer exist upstream.
for (const existing of readdirSync(DEST)) {
  if (existing.endsWith(".json") && !entries.some((e) => e.file === existing)) unlinkSync(path.join(DEST, existing));
}

const ident = (id) => "t_" + id.replace(/[^a-zA-Z0-9]+/g, "_");
const lines = [
  "// Generated by scripts/sync-tech-sheets.mjs — do not edit by hand; re-run the script instead.",
  'import { TechSheetTemplate } from "@/data/techSheetTypes";',
  ...entries.map((e) => `import ${ident(e.id)} from "./${e.file}";`),
  "",
  "/** Built-in tech sheet templates, copied from the Digital logbooks app (logbook-app/tech-sheets/templates). */",
  "export const BUILTIN_TECH_SHEETS: TechSheetTemplate[] = [",
  ...entries.map((e) => `  ${ident(e.id)} as unknown as TechSheetTemplate,`),
  "];",
  "",
];
writeFileSync(path.join(DEST, "index.ts"), lines.join("\n"));
console.log(`Synced ${entries.length} template(s): ${entries.map((e) => e.id).join(", ")}`);
